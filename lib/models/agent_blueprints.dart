/// A single turn in the Antigravity Co-Design Chat thread.
class AgentChatMessage {
  final String id;
  final String role; // 'user' or 'assistant'
  final String text;
  final List<String> quickReplies;
  final List<String> updatedFields;
  final String? modelUsed;

  const AgentChatMessage({
    required this.id,
    required this.role,
    required this.text,
    this.quickReplies = const [],
    this.updatedFields = const [],
    this.modelUsed,
  });

  bool get isUser => role == 'user';

  Map<String, dynamic> toJson() => {
        'id': id,
        'role': role,
        'text': text,
        'quickReplies': quickReplies,
        'updatedFields': updatedFields,
        if (modelUsed != null) 'modelUsed': modelUsed,
      };

  factory AgentChatMessage.fromJson(Map<String, dynamic> json) {
    return AgentChatMessage(
      id: json['id']?.toString() ?? 'msg',
      role: json['role']?.toString() ?? 'assistant',
      text: json['text']?.toString() ?? '',
      quickReplies: (json['quickReplies'] as List?)
              ?.map((e) => e.toString())
              .toList() ??
          const <String>[],
      updatedFields: (json['updatedFields'] as List?)
              ?.map((e) => e.toString())
              .toList() ??
          const <String>[],
      modelUsed: json['modelUsed']?.toString(),
    );
  }
}

/// Represents a multiple-choice clarifying question generated by an Agent,
/// modeled after Antigravity's interactive `ask_question` tool.
class AgentQuestion {
  final String id;
  final String question;
  final List<String> options;
  final bool isMultiSelect;
  String selectedOption;
  String customWriteIn;

  AgentQuestion({
    required this.id,
    required this.question,
    required this.options,
    this.isMultiSelect = false,
    String? selectedOption,
    this.customWriteIn = '',
  }) : selectedOption = selectedOption ?? (options.isNotEmpty ? options.first : '');

  /// Effective user answer (prefers customWriteIn if non-empty).
  String get effectiveAnswer =>
      customWriteIn.trim().isNotEmpty ? customWriteIn.trim() : selectedOption;

  Map<String, dynamic> toJson() => {
        'id': id,
        'question': question,
        'options': options,
        'isMultiSelect': isMultiSelect,
        'selectedOption': selectedOption,
        'customWriteIn': customWriteIn,
      };

  factory AgentQuestion.fromJson(Map<String, dynamic> json) {
    final opts = (json['options'] as List?)?.map((e) => e.toString()).toList() ?? const <String>[];
    return AgentQuestion(
      id: json['id']?.toString() ?? 'q',
      question: json['question']?.toString() ?? '',
      options: opts,
      isMultiSelect: json['isMultiSelect'] == true,
      selectedOption: json['selectedOption']?.toString(),
      customWriteIn: json['customWriteIn']?.toString() ?? '',
    );
  }
}

/// Sequential production phase tracks in the Rolling Phase Release model:
/// 1. Prototype -> 2. MVP Track (1 Release per Beat) -> 3. Vertical Slice -> 4. Full Production.
enum ProductionPhase {
  prototype(
    label: 'PHASE 1 · PROTOTYPE',
    shortName: 'Prototype',
    summary: 'Define and playtest the Core Game Loop in a greybox sandbox.',
    unlockCondition: 'Active in Stage 1',
  ),
  mvp(
    label: 'PHASE 2 · MVP RELEASES',
    shortName: 'MVP Track',
    summary: 'Build 1 focused MVP Release for each proven Core Loop Beat.',
    unlockCondition: 'Unlocks after Prototype completes',
  ),
  verticalSlice(
    label: 'PHASE 3 · VERTICAL SLICE',
    shortName: 'Vertical Slice',
    summary: 'Combine all completed MVP Beats into 1 fully polished Gold Standard level.',
    unlockCondition: 'Unlocks after all MVP Releases complete',
  ),
  fullProduction(
    label: 'PHASE 4 · FULL PRODUCTION',
    shortName: 'Full Production',
    summary: 'Reuse the Rough → Polish release pattern across the remaining world and content.',
    unlockCondition: 'Unlocks after Vertical Slice completes',
  );

  final String label;
  final String shortName;
  final String summary;
  final String unlockCondition;

  const ProductionPhase({
    required this.label,
    required this.shortName,
    required this.summary,
    required this.unlockCondition,
  });
}

/// Blueprint produced during Stage 1 (Initial Project Concept Creation).
/// Combines the 9-section structured Project Concept (`Goal`, `Game Spec`,
/// `Tech Spec`, `Design Pillars`, `Trade-Offs`, `Core Loop`, `Out of Scope`,
/// `Done When`, `Prototype Release`) with section-focused Agent guidance.
class ProjectConceptBlueprint {
  String title;
  String sparkIdea;
  List<AgentQuestion> questions;
  String goal;
  List<String> gameSpec;
  List<String> techSpec;
  List<String> designPillars;
  List<String> tradeOffs;
  List<String> coreLoopBeats;
  List<String> exclusions;
  String doneWhen;
  ReleaseScope firstReleasePreset;
  List<String> releaseTrainTitles;
  bool isInterviewComplete;
  List<AgentChatMessage> chatHistory;
  List<String> lastUpdatedFields;
  Map<String, List<String>> sectionOptions;

  ProjectConceptBlueprint({
    required this.title,
    required this.sparkIdea,
    required this.questions,
    required this.goal,
    this.gameSpec = const [
      '2D Top-Down',
      'Twin-Stick (WASD + Aim)',
      'Singleplayer',
      'Single-Screen Wave Arena',
    ],
    this.techSpec = const [
      'Godot 4 (2D)',
      'PC (Steam / Desktop)',
      '2D Sprites + Particles',
      'Offline-Only Local Save',
    ],
    this.designPillars = const [
      'Every cycle rewards decisive movement and timing over hesitation',
      'Mistakes feel immediately readable and recoverable in a single button press',
      'Core controls feel responsive from the very first second on screen',
    ],
    this.tradeOffs = const [
      'Immediate arcade responsiveness over realistic physics inertia',
      'Readable greybox clarity over complex visual shaders in v0.1',
      'Fast 1-key loop reset over multi-screen menu flows',
    ],
    required this.coreLoopBeats,
    required this.exclusions,
    required this.doneWhen,
    this.firstReleasePreset = ReleaseScope.featurePrototype,
    required this.releaseTrainTitles,
    this.isInterviewComplete = false,
    List<AgentChatMessage>? chatHistory,
    this.lastUpdatedFields = const [],
    Map<String, List<String>>? sectionOptions,
  })  : chatHistory = chatHistory ?? <AgentChatMessage>[],
        sectionOptions = sectionOptions ?? <String, List<String>>{};

  /// Formats the Project Concept into the strict 3-part Scope & Goal layout.
  String toFormattedScopeSection() {
    final inScopeLines = coreLoopBeats.map((b) => '• $b').join('\n');
    final outScopeLines = exclusions.map((e) => '• $e').join('\n');
    return 'Goal: $goal\n\n'
        'In Scope:\n$inScopeLines\n\n'
        'Out of Scope:\n$outScopeLines\n\n'
        'Done When: $doneWhen';
  }

  Map<String, dynamic> toJson() => {
        'title': title,
        'sparkIdea': sparkIdea,
        'questions': questions.map((q) => q.toJson()).toList(),
        'goal': goal,
        'gameSpec': gameSpec,
        'techSpec': techSpec,
        'designPillars': designPillars,
        'tradeOffs': tradeOffs,
        'coreLoopBeats': coreLoopBeats,
        'exclusions': exclusions,
        'doneWhen': doneWhen,
        'firstReleasePreset': firstReleasePreset.name,
        'releaseTrainTitles': releaseTrainTitles,
        'isInterviewComplete': isInterviewComplete,
        'chatHistory': chatHistory.map((m) => m.toJson()).toList(),
        'lastUpdatedFields': lastUpdatedFields,
        'sectionOptions': sectionOptions,
      };

  factory ProjectConceptBlueprint.fromJson(Map<String, dynamic> json) {
    final rawOpts = json['sectionOptions'] as Map<String, dynamic>?;
    final parsedOpts = <String, List<String>>{};
    if (rawOpts != null) {
      rawOpts.forEach((key, value) {
        if (value is List) {
          parsedOpts[key] = value.map((e) => e.toString()).toList();
        }
      });
    }
    return ProjectConceptBlueprint(
      title: json['title']?.toString() ?? 'Untitled Project',
      sparkIdea: json['sparkIdea']?.toString() ?? '',
      questions: (json['questions'] as List?)
              ?.whereType<Map<String, dynamic>>()
              .map(AgentQuestion.fromJson)
              .toList() ??
          <AgentQuestion>[],
      goal: json['goal']?.toString() ?? '',
      gameSpec: (json['gameSpec'] as List?)
              ?.map((e) => e.toString())
              .toList() ??
          const [
            '2D Top-Down',
            'Twin-Stick (WASD + Aim)',
            'Singleplayer',
            'Single-Screen Wave Arena',
          ],
      techSpec: (json['techSpec'] as List?)
              ?.map((e) => e.toString())
              .toList() ??
          const [
            'Godot 4 (2D)',
            'PC (Steam / Desktop)',
            '2D Sprites + Particles',
            'Offline-Only Local Save',
          ],
      designPillars: (json['designPillars'] as List?)
              ?.map((e) => e.toString())
              .toList() ??
          const <String>[],
      tradeOffs: (json['tradeOffs'] as List?)
              ?.map((e) => e.toString())
              .toList() ??
          const <String>[],
      coreLoopBeats: (json['coreLoopBeats'] as List?)
              ?.map((e) => e.toString())
              .toList() ??
          <String>[],
      exclusions: (json['exclusions'] as List?)
              ?.map((e) => e.toString())
              .toList() ??
          <String>[],
      doneWhen: json['doneWhen']?.toString() ?? '',
      firstReleasePreset: ReleaseScope.values.firstWhere(
        (s) => s.name == json['firstReleasePreset'],
        orElse: () => ReleaseScope.featurePrototype,
      ),
      releaseTrainTitles: (json['releaseTrainTitles'] as List?)
              ?.map((e) => e.toString())
              .toList() ??
          <String>['v0.1: Core Movement & Game Loop - Prototype'],
      isInterviewComplete: json['isInterviewComplete'] == true,
      chatHistory: (json['chatHistory'] as List?)
              ?.whereType<Map<String, dynamic>>()
              .map(AgentChatMessage.fromJson)
              .toList() ??
          <AgentChatMessage>[],
      lastUpdatedFields: (json['lastUpdatedFields'] as List?)
              ?.map((e) => e.toString())
              .toList() ??
          const <String>[],
      sectionOptions: parsedOpts,
    );
  }
}

/// Lifecycle state of a Feature across evolving releases (`v0.1` -> `v0.2` -> `v1.0+`).
enum FeatureLifecycleStatus {
  /// Newly introduced in this release (or promoted from prior Out of Scope).
  newFeature,

  /// Built in an earlier release and receiving new upgrade Checkpoints in this release.
  upgrade,

  /// Built in an earlier release and untouched in this release (`0h` delta work).
  stable,

  /// Temporary testbed from an earlier release superseded by a real system in this release.
  superseded;

  static FeatureLifecycleStatus fromString(String? raw) {
    final clean = (raw ?? '').trim().toLowerCase();
    if (clean.contains('upgrade') || clean.contains('evolve')) {
      return FeatureLifecycleStatus.upgrade;
    }
    if (clean.contains('stable') || clean.contains('frozen')) {
      return FeatureLifecycleStatus.stable;
    }
    if (clean.contains('supersed') || clean.contains('retire') || clean.contains('archive')) {
      return FeatureLifecycleStatus.superseded;
    }
    return FeatureLifecycleStatus.newFeature;
  }
}

/// A proposed Feature stub inside a Release Blueprint Beat.
/// The user can toggle `included` on/off at the Confirmation Gate;
/// unchecked features automatically move into `Out of Scope` (YAGNI).
class ProposedFeatureBlueprint {
  final String id;
  String title;
  String goal;
  String doneWhen;
  int estimatedHours;
  bool included;
  FeatureLifecycleStatus lifecycle;
  String originVersion;
  String? supersedesFeatureTitle;
  List<String> inScope;
  List<String> outOfScope;
  List<String> tuningParams;
  List<String> edgeCases;
  List<ProposedCheckpointBlueprint> checkpoints;

  ProposedFeatureBlueprint({
    required this.id,
    required this.title,
    required this.goal,
    required this.doneWhen,
    this.estimatedHours = 4,
    this.included = true,
    this.lifecycle = FeatureLifecycleStatus.newFeature,
    this.originVersion = 'v0.1',
    this.supersedesFeatureTitle,
    this.inScope = const [],
    this.outOfScope = const [],
    this.tuningParams = const [],
    this.edgeCases = const [],
    this.checkpoints = const [],
  });

  bool get isStable => lifecycle == FeatureLifecycleStatus.stable;
  bool get isSuperseded => lifecycle == FeatureLifecycleStatus.superseded;
  int get activeDeltaHours =>
      (!included || isStable || isSuperseded) ? 0 : estimatedHours;

  Map<String, dynamic> toJson() => {
        'id': id,
        'title': title,
        'goal': goal,
        'doneWhen': doneWhen,
        'estimatedHours': estimatedHours,
        'included': included,
        'lifecycle': lifecycle.name,
        'originVersion': originVersion,
        if (supersedesFeatureTitle != null)
          'supersedesFeatureTitle': supersedesFeatureTitle,
        'inScope': inScope,
        'outOfScope': outOfScope,
        'tuningParams': tuningParams,
        'edgeCases': edgeCases,
        'checkpoints': checkpoints.map((c) => c.toJson()).toList(),
      };

  factory ProposedFeatureBlueprint.fromJson(Map<String, dynamic> json) {
    return ProposedFeatureBlueprint(
      id: json['id']?.toString() ?? 'feat',
      title: json['title']?.toString() ?? '',
      goal: json['goal']?.toString() ?? '',
      doneWhen: json['doneWhen']?.toString() ?? '',
      estimatedHours: (json['estimatedHours'] as num?)?.toInt() ?? 4,
      included: json['included'] != false,
      lifecycle: FeatureLifecycleStatus.fromString(json['lifecycle']?.toString()),
      originVersion: json['originVersion']?.toString() ?? 'v0.1',
      supersedesFeatureTitle: json['supersedesFeatureTitle']?.toString(),
      inScope: (json['inScope'] as List?)
              ?.map((e) => e.toString())
              .toList() ??
          const <String>[],
      outOfScope: (json['outOfScope'] as List?)
              ?.map((e) => e.toString())
              .toList() ??
          const <String>[],
      tuningParams: (json['tuningParams'] as List?)
              ?.map((e) => e.toString())
              .toList() ??
          const <String>[],
      edgeCases: (json['edgeCases'] as List?)
              ?.map((e) => e.toString())
              .toList() ??
          const <String>[],
      checkpoints: (json['checkpoints'] as List?)
              ?.whereType<Map<String, dynamic>>()
              .map(ProposedCheckpointBlueprint.fromJson)
              .toList() ??
          const <ProposedCheckpointBlueprint>[],
    );
  }
}

