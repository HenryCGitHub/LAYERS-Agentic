/// A proposed Core Loop Beat (Tier 3 Epic) inside a Release Blueprint.
class ProposedBeatBlueprint {
  final String id;
  String title;
  String goal;
  String doneWhen;
  List<ProposedFeatureBlueprint> features;

  ProposedBeatBlueprint({
    required this.id,
    required this.title,
    required this.goal,
    required this.doneWhen,
    required this.features,
  });

  List<ProposedFeatureBlueprint> get includedFeatures =>
      features.where((f) => f.included && !f.isSuperseded).toList();

  List<ProposedFeatureBlueprint> get deferredFeatures =>
      features.where((f) => !f.included && !f.isSuperseded).toList();

  int get totalIncludedHours =>
      includedFeatures.fold(0, (sum, f) => sum + f.activeDeltaHours);

  Map<String, dynamic> toJson() => {
        'id': id,
        'title': title,
        'goal': goal,
        'doneWhen': doneWhen,
        'features': features.map((f) => f.toJson()).toList(),
      };

  factory ProposedBeatBlueprint.fromJson(Map<String, dynamic> json) {
    return ProposedBeatBlueprint(
      id: json['id']?.toString() ?? 'beat',
      title: json['title']?.toString() ?? '',
      goal: json['goal']?.toString() ?? '',
      doneWhen: json['doneWhen']?.toString() ?? '',
      features: (json['features'] as List?)
              ?.whereType<Map<String, dynamic>>()
              .map(ProposedFeatureBlueprint.fromJson)
              .toList() ??
          <ProposedFeatureBlueprint>[],
    );
  }
}

/// Blueprint produced by `ReleasePlannerAgent` for the Confirmation Gate (Stage 2).
class ReleaseBlueprint {
  final String releaseDocId;
  String releaseTitle;
  String releaseVersionTag;
  ReleaseScope preset;
  String goal;
  String doneWhen;
  List<AgentQuestion> questions;
  List<ProposedBeatBlueprint> beats;
  List<String> explicitExclusions;
  List<AgentChatMessage> chatHistory;

  ReleaseBlueprint({
    required this.releaseDocId,
    required this.releaseTitle,
    this.releaseVersionTag = 'v0.1',
    this.preset = ReleaseScope.featurePrototype,
    required this.goal,
    required this.doneWhen,
    required this.questions,
    required this.beats,
    this.explicitExclusions = const [],
    List<AgentChatMessage>? chatHistory,
  }) : chatHistory = chatHistory ?? <AgentChatMessage>[];

  /// Total active delta hours of all currently checked/included Features across all Beats.
  int get totalIncludedHours =>
      beats.fold(0, (sum, b) => sum + b.totalIncludedHours);

  /// Total hours of all deferred (unchecked, non-superseded) Features across all Beats.
  int get totalDeferredHours => beats.fold(
        0,
        (sum, b) => sum + b.deferredFeatures.fold(0, (s, f) => s + f.estimatedHours),
      );

  /// Count of included Features across all Beats (excluding superseded ones).
  int get totalIncludedFeatures =>
      beats.fold(0, (sum, b) => sum + b.includedFeatures.length);

  /// Count of deferred Features across all Beats (excluding superseded ones).
  int get totalDeferredFeatures =>
      beats.fold(0, (sum, b) => sum + b.deferredFeatures.length);

  /// Combines explicit exclusions + any Features the user unchecked at the Confirmation Gate.
  List<String> get effectiveOutOfScope {
    final out = <String>[...explicitExclusions];
    for (final beat in beats) {
      for (final deferred in beat.deferredFeatures) {
        final label = '${deferred.title} (deferred from ${beat.title})';
        if (!out.contains(label)) {
          out.add(label);
        }
      }
    }
    return out;
  }

  Map<String, dynamic> toJson() => {
        'releaseDocId': releaseDocId,
        'releaseTitle': releaseTitle,
        'releaseVersionTag': releaseVersionTag,
        'preset': preset.name,
        'goal': goal,
        'doneWhen': doneWhen,
        'questions': questions.map((q) => q.toJson()).toList(),
        'beats': beats.map((b) => b.toJson()).toList(),
        'explicitExclusions': explicitExclusions,
        'chatHistory': chatHistory.map((m) => m.toJson()).toList(),
      };

  factory ReleaseBlueprint.fromJson(Map<String, dynamic> json) {
    return ReleaseBlueprint(
      releaseDocId: json['releaseDocId']?.toString() ?? 'rel_v0_1',
      releaseTitle: json['releaseTitle']?.toString() ?? 'v0.1: Prototype',
      releaseVersionTag: json['releaseVersionTag']?.toString() ?? 'v0.1',
      preset: ReleaseScope.values.firstWhere(
        (s) => s.name == json['preset'],
        orElse: () => ReleaseScope.featurePrototype,
      ),
      goal: json['goal']?.toString() ?? '',
      doneWhen: json['doneWhen']?.toString() ?? '',
      questions: (json['questions'] as List?)
              ?.whereType<Map<String, dynamic>>()
              .map(AgentQuestion.fromJson)
              .toList() ??
          <AgentQuestion>[],
      beats: (json['beats'] as List?)
              ?.whereType<Map<String, dynamic>>()
              .map(ProposedBeatBlueprint.fromJson)
              .toList() ??
          <ProposedBeatBlueprint>[],
      explicitExclusions: (json['explicitExclusions'] as List?)
              ?.map((e) => e.toString())
              .toList() ??
          const <String>[],
      chatHistory: (json['chatHistory'] as List?)
              ?.whereType<Map<String, dynamic>>()
              .map(AgentChatMessage.fromJson)
              .toList() ??
          <AgentChatMessage>[],
    );
  }
}
